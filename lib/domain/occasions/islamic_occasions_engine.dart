import '../calculation/hijri_calculator.dart';

/// Represents a contextual Islamic occasion active on a given day.
class IslamicOccasion {
  final String titleAr;
  final String? messageAr;
  final String? hadithAr;
  final String? primaryDuaAr;
  final List<String> duasAr;
  final OccasionType type;

  const IslamicOccasion({
    required this.titleAr,
    this.messageAr,
    this.hadithAr,
    this.primaryDuaAr,
    this.duasAr = const [],
    required this.type,
  });
}

enum OccasionType {
  ramadan,
  eidFitr,
  eidAdha,
  arafah,
  ashura,
  friday,
  mawlid,
  islamicNewYear,
}

/// Detects active Islamic occasions based on Hijri date.
class IslamicOccasionsEngine {
  /// Returns all occasions active on the given Gregorian [date].
  static List<IslamicOccasion> getOccasions(
    DateTime date, {
    int hijriOffsetDays = 0,
  }) {
    final hijri = HijriCalculator.calculate(
      gregorianDate: date,
      offsetDays: hijriOffsetDays,
    );
    final occasions = <IslamicOccasion>[];

    final m = hijri.month;
    final d = hijri.day;
    final weekday = date.weekday; // 1=Mon, 5=Fri, 7=Sun

    // ── Friday ──────────────────────────────────────────────────────────────
    if (weekday == DateTime.friday) {
      occasions.add(const IslamicOccasion(
        titleAr: 'الجمعة المباركة',
        messageAr:
            'اقرأ سورة الكهف وأكثر من الصلاة على النبي ﷺ وسل الله من فضله في ساعة الإجابة',
        hadithAr:
            'قال رسول الله ﷺ: «إِنَّ فِي الْجُمُعَةِ لَسَاعَةً لَا يُوَافِقُهَا عَبْدٌ مُسْلِمٌ يَسْأَلُ اللَّهَ شَيْئًا إِلَّا أَعْطَاهُ إِيَّاهُ» (متفق عليه)',
        primaryDuaAr:
            '«اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى نَبِيِّنَا مُحَمَّدٍ، اللَّهُمَّ اغْفِرْ لَنَا فِي هَذِهِ السَّاعَةِ الْمُبَارَكَةِ، وَاشْرَحْ صُدُورَنَا وَيَسِّرْ أُمُورَنَا وَتَقَبَّلْ دُعَاءَنَا»',
        duasAr: [
          '«اللَّهُمَّ صَلِّ عَلَى مُحَمَّدٍ وَعَلَى آلِ مُحَمَّدٍ كَمَا صَلَّيْتَ عَلَى إِبْرَاهِيمَ وَعَلَى آلِ إِبْرَاهِيمَ إِنَّكَ حَمِيدٌ مَجِيدٌ»',
          '«اللَّهُمَّ فِي يَوْمِ الْجُمُعَةِ عَافِ كُلَّ مَرِيضٍ، وَارْحَمْ كُلَّ مَيِّتٍ، وَفَرِّجْ هَمَّ كُلِّ مَهْمُومٍ، وَاجْعَلْ لَنَا مِنْ كُلِّ ضِيقٍ مَخْرَجًا»',
          '«يَا رَبِّ لَا تَدَعْ لَنَا فِي هَذَا الْيَوْمِ الْمُبَارَكِ ذَنْبًا إِلَّا غَفَرْتَهُ، وَلَا هَمًّا إِلَّا فَرَّجْتَهُ، وَلَا دَيْنًا إِلَّا قَضَيْتَهُ»',
          '«مَنْ قَرَأَ سُورَةَ الْكَهْفِ فِي يَوْمِ الْجُمُعَةِ أَضَاءَ لَهُ مِنَ النُّورِ مَا بَيْنَ الْجُمُعَتَيْنِ»',
          '«اللَّهُمَّ احْفَظْ بِلَادَنَا الْجَزَائِرَ وَسَائِرَ بِلَادِ الْمُسْلِمِينَ مِنَ الْفِتَنِ وَسُوءِ الْمَحْيَا وَالْمَمَاتِ»',
        ],
        type: OccasionType.friday,
      ));
    }

    // ── Ramadan (month 9) ───────────────────────────────────────────────────
    if (m == 9) {
      final isLaylat = (d == 21 || d == 23 || d == 25 || d == 27 || d == 29);
      occasions.add(IslamicOccasion(
        titleAr: 'رمضان المبارك — اليوم $d',
        messageAr: isLaylat
            ? 'العشر الأواخر: ليلة القدر خير من ألف شهر، فاغتنموها بالقيام والدعاء'
            : 'شهر الصيام والقرآن والرحمة والمغفرة والعتق من النيران',
        hadithAr:
            'قال رسول الله ﷺ: «مَنْ صَامَ رَمَضَانَ إِيمَانًا وَاحْتِسَابًا غُفِرَ لَهُ مَا تَقَدَّمَ مِنْ ذَنْبِهِ» (متفق عليه)',
        primaryDuaAr: isLaylat
            ? '«اللَّهُمَّ إِنَّكَ عَفُوٌّ كَرِيمٌ تُحِبُّ الْعَفْوَ فَاعْفُ عَنِّي»'
            : '«اللَّهُمَّ لَكَ صُمْتُ، وَعَلَى رِزْقِكَ أَفْطَرْتُ، ذَهَبَ الظَّمَأُ وَابْتَلَّتِ الْعُرُوقُ وَثَبَتَ الْأَجْرُ إِنْ شَاءَ اللَّهُ»',
        duasAr: const [
          '«اللَّهُمَّ إِنَّكَ عَفُوٌّ كَرِيمٌ تُحِبُّ الْعَفْوَ فَاعْفُ عَنِّي» (دعاء ليلة القدر)',
          '«اللَّهُمَّ اجْعَلْ صِيَامَنَا صِيَامَ الصَّائِمِينَ، وَقِيَامَنَا قِيَامَ الْقَائِمِينَ، وَأَعْتِقْ رِقَابَنَا وَآبَائِنَا مِنَ النَّارِ»',
          '«رَبَّنَا تَقَبَّلْ مِنَّا صِيَامَنَا وَقِيَامَنَا وَرُكُوعَنَا وَسُجُودَنَا، وَاخْتِمْ لَنَا شَهْرَ رَمَضَانَ بِرِضْوَانِكَ»',
          '«اللَّهُمَّ سَلِّمْنَا لِرَمَضَانَ وَسَلِّمْ رَمَضَانَ لَنَا وَتَسَلَّمْهُ مِنَّا مُتَقَبَّلًا يَا أَرْحَمَ الرَّاحِمِينَ»',
        ],
        type: OccasionType.ramadan,
      ));
    }

    // ── Eid al-Fitr (1-3 Shawwal) ───────────────────────────────────────────
    if (m == 10 && d >= 1 && d <= 3) {
      occasions.add(const IslamicOccasion(
        titleAr: 'عيد الفطر المبارك',
        messageAr: 'عيد مبارك سعيد — تقبل الله منا ومنكم صالح الأعمال والطاعات',
        hadithAr:
            '«كَانَ أَصْحَابُ رَسُولِ اللهِ ﷺ إِذَا الْتَقَوْا يَوْمَ الْعِيدِ يَقُولُ بَعْضُهُمْ لِبَعْضٍ: تَقَبَّلَ اللهُ مِنَّا وَمِنْكَ»',
        primaryDuaAr:
            '«اللهُ أَكْبَرُ، اللهُ أَكْبَرُ، اللهُ أَكْبَرُ، لَا إِلَهَ إِلَّا اللهُ، اللهُ أَكْبَرُ، اللهُ أَكْبَرُ، وَلِلَّهِ الْحَمْدُ»',
        duasAr: [
          '«اللهُ أَكْبَرُ، اللهُ أَكْبَرُ، اللهُ أَكْبَرُ، لَا إِلَهَ إِلَّا اللهُ، اللهُ أَكْبَرُ، اللهُ أَكْبَرُ، وَلِلَّهِ الْحَمْدُ»',
          '«اللهُ أَكْبَرُ كَبِيرًا، وَالْحَمْدُ لِلَّهِ كَثِيرًا، وَسُبْحَانَ اللهِ بُكْرَةً وَأَصِيلًا»',
          '«تَقَبَّلَ اللهُ مِنَّا وَمِنْكُمُ الصِّيَامَ وَالْقِيَامَ، وَجَعَلَنَا وَإِيَّاكُمْ مِنَ الْعَائِدِينَ الْفَائِزِينَ الْمَقْبُولِينَ»',
          '«اللَّهُمَّ أَدْخِلْ عَلَى أَهْلِ الْإِسْلَامِ فِي كُلِّ مَكَانٍ السُّرُورَ وَالْأَمْنَ وَالْبَرَكَةَ، وَأَعِدْهُ عَلَيْنَا أَعْوَامًا عَدِيدَةً»',
        ],
        type: OccasionType.eidFitr,
      ));
    }

    // ── Day of Arafah (9 Dhu al-Hijjah) ─────────────────────────────────────
    if (m == 12 && d == 9) {
      occasions.add(const IslamicOccasion(
        titleAr: 'يوم عرفة المبارك',
        messageAr: 'يوم المغفرة والعتق من النيران — يُستحب صيامه والإكثار من الدعاء فيه',
        hadithAr:
            'قال رسول الله ﷺ: «صِيَامُ يَوْمِ عَرَفَةَ أَحْتَسِبُ عَلَى اللهِ أَنْ يُكَفِّرَ السَّنَةَ الَّتِي قَبْلَهُ وَالسَّنَةَ الَّتِي بَعْدَهُ» (صحيح مسلم)',
        primaryDuaAr:
            '«لَا إِلَهَ إِلَّا اللهُ وَحْدَهُ لَا شَرِيكَ لَهُ، لَهُ الْمُلْكُ وَلَهُ الْحَمْدُ، وَهُوَ عَلَى كُلِّ شَيْءٍ قَدِيرٌ»',
        duasAr: [
          '«خَيْرُ الدُّعَاءِ دُعَاءُ يَوْمِ عَرَفَةَ: لَا إِلَهَ إِلَّا اللهُ وَحْدَهُ لَا شَرِيكَ لَهُ، لَهُ الْمُلْكُ وَلَهُ الْحَمْدُ، وَهُوَ عَلَى كُلِّ شَيْءٍ قَدِيرٌ»',
          '«اللَّهُمَّ إِنِّي أَسْأَلُكَ فِي يَوْمِ عَرَفَةَ أَنْ تَبْسُطَ عَلَيْنَا مِنْ بَرَكَاتِكَ وَرَحْمَتِكَ، وَأَنْ تُعْتِقَ رِقَابَنَا مِنَ النَّارِ»',
          '«رَبَّنَا آتِنَا فِي الدُّنْيَا حَسَنَةً وَفِي الْآخِرَةِ حَسَنَةً وَقِنَا عَذَابَ النَّارِ»',
          '«اللَّهُمَّ اغْفِرْ لِحُجَّاجِ بَيْتِكَ الْحَرَامِ وَلِمَنِ اسْتَغْفَرَ لَهُ الْحَاجُّ، وَتَقَبَّلْ مِنْهُمْ حَجَّهُمْ وَسَعْيَهُمْ»',
        ],
        type: OccasionType.arafah,
      ));
    }

    // ── Eid al-Adha (10-13 Dhu al-Hijjah) ───────────────────────────────────
    if (m == 12 && d >= 10 && d <= 13) {
      occasions.add(const IslamicOccasion(
        titleAr: 'عيد الأضحى المبارك وأيام التشريق',
        messageAr: 'أيام أكل وشرب وذكر لله تعالى — تقبل الله منا ومنكم الأضاحي والطاعات',
        hadithAr:
            'قال رسول الله ﷺ: «أَعْظَمُ الْأَيَّامِ عِنْدَ اللهِ تَبَارَكَ وَتَعَالَى يَوْمُ النَّحْرِ، ثُمَّ يَوْمُ الْقَرِّ» (رواه أبو داود)',
        primaryDuaAr:
            '«اللهُ أَكْبَرُ، اللهُ أَكْبَرُ، اللهُ أَكْبَرُ، لَا إِلَهَ إِلَّا اللهُ، اللهُ أَكْبَرُ، اللهُ أَكْبَرُ، وَلِلَّهِ الْحَمْدُ»',
        duasAr: [
          '«اللهُ أَكْبَرُ، اللهُ أَكْبَرُ، اللهُ أَكْبَرُ، لَا إِلَهَ إِلَّا اللهُ، اللهُ أَكْبَرُ، اللهُ أَكْبَرُ، وَلِلَّهِ الْحَمْدُ»',
          '«تَقَبَّلَ اللهُ مِنَّا وَمِنْكُمُ الضَّحَايَا وَصَالِحَ الْأَعْمَالِ، وَجَعَلَ أَيَّامَكُمْ أَيَّامَ خَيْرٍ وَتَوْحِيدٍ وَبَرَكَةٍ»',
          '«اللهُ أَكْبَرُ كَبِيرًا، وَالْحَمْدُ لِلَّهِ كَثِيرًا، وَسُبْحَانَ اللهِ بُكْرَةً وَأَصِيلًا»',
          '«اللَّهُمَّ اجْعَلْ أَيَّامَ التَّشْرِيقِ أَيَّامَ ذِكْرٍ وَشُكْرٍ وَحُسْنِ عِبَادَةٍ، وَانْشُرِ السَّلَامَ فِي رُبُوعِ أُمَّتِنَا»',
        ],
        type: OccasionType.eidAdha,
      ));
    }

    // ── Ashura (9-10 Muharram) ──────────────────────────────────────────────
    if (m == 1 && (d == 9 || d == 10)) {
      occasions.add(const IslamicOccasion(
        titleAr: 'يوم عاشوراء المبارك',
        messageAr: 'يوم نجاة موسى عليه السلام — يُستحب صيامه وصيام يوم قبله أو بعده',
        hadithAr:
            'قال رسول الله ﷺ: «صِيَامُ يَوْمِ عَاشُورَاءَ أَحْتَسِبُ عَلَى اللهِ أَنْ يُكَفِّرَ السَّنَةَ الَّتِي قَبْلَهُ» (صحيح مسلم)',
        primaryDuaAr:
            '«اللَّهُمَّ يَا فَاَرِجَ الْهَمِّ، وَيَا كَاشِفَ الْغَمِّ، نَجِّنَا مِنْ فِتَنِ الدُّنْيَا، وَاغْفِرْ لَنَا مَغْفِرَةً تُطَهِّرُ بِهَا قُلُوبَنَا»',
        duasAr: [
          '«اللَّهُمَّ يَا مُنَجِّيَ مُوسَى وَقَوْمَهُ مِنَ الْغَرَقِ، فَرِّجْ كُرُوبَنَا وَانْصُرْنَا عَلَى الْقَوْمِ الظَّالِمِينَ»',
          '«رَبَّنَا اغْفِرْ لَنَا ذُنُوبَنَا وَإِسْرَافَنَا فِي أَمْرِنَا وَثَبِّتْ أَقْدَامَنَا وَانصُرْنَا عَلَى الْقَوْمِ الْكَافِرِينَ»',
          '«اللَّهُمَّ إِنَّا نَسْأَلُكَ خَيْرَ هَذَا الشَّهْرِ الْمُحَرَّمِ وَفَتْحَهُ وَنَصْرَهُ وَنُورَهُ وَبَرَكَتَهُ وَهُدَاهُ»',
        ],
        type: OccasionType.ashura,
      ));
    }

    // ── Mawlid al-Nabawi (12 Rabi' al-Awwal) ────────────────────────────────
    if (m == 3 && d == 12) {
      occasions.add(const IslamicOccasion(
        titleAr: 'ذكرى المولد النبوي الشريف',
        messageAr: 'مولد الهدى والرحمة المهداة للعالمين ﷺ — أكثروا من الصلاة والسلام عليه',
        hadithAr:
            'قال رسول الله ﷺ: «مَنْ صَلَّى عَلَيَّ صَلَاةً صَلَّى اللَّهُ عَلَيْهِ بِهَا عَشْرًا» (صحيح مسلم)',
        primaryDuaAr:
            '«اللَّهُمَّ صَلِّ وَسَلِّمْ وَبَارِكْ عَلَى نَبِيِّنَا وَحَبِيبِنَا وَقُدْوَتِنَا مُحَمَّدٍ رَسُولِ اللهِ ﷺ، وَعَلَى آلِهِ وَصَحْبِهِ أَجْمَعِينَ»',
        duasAr: [
          '«اللَّهُمَّ اجْزِ عَنَّا نَبِيَّنَا مُحَمَّدًا ﷺ خَيْرَ مَا جَزَيْتَ نَبِيًّا عَنْ أُمَّتِهِ، وَارْزُقْنَا شَفَاعَتَهُ يَوْمَ الْقِيَامَةِ»',
          '«اللَّهُمَّ احْشُرْنَا فِي زُمْرَتِهِ، وَأَوْرِدْنَا حَوْضَهُ الشَّرِيفَ، وَاسْقِنَا بِيَدِهِ شَرْبَةً هَنِيئَةً لَا نَظْمَأُ بَعْدَهَا أَبَدًا»',
          '«اللَّهُمَّ أَحْيِنَا عَلَى سُنَّتِهِ، وَتَوَفَّنَا عَلَى مِلَّتِهِ، وَأَلْحِقْنَا بِهِ فِي الْفِرْدَوْسِ الْأَعْلَى مِنَ الْجَنَّةِ»',
        ],
        type: OccasionType.mawlid,
      ));
    }

    // ── Islamic New Year (1 Muharram) ────────────────────────────────────────
    if (m == 1 && d == 1) {
      occasions.add(IslamicOccasion(
        titleAr: 'رأس السنة الهجرية ${hijri.year} هـ',
        messageAr: 'غرة المحرم فاتح العام الهجري — نسأل الله أن يجعله عام أمن وبركة ونصر',
        hadithAr:
            'قال رسول الله ﷺ: «أَفْضَلُ الصِّيَامِ بَعْدَ رَمَضَانَ شَهْرُ اللَّهِ الْمُحَرَّمُ» (صحيح مسلم)',
        primaryDuaAr:
            '«اللَّهُمَّ أَدْخِلْهُ عَلَيْنَا بِالْأَمْنِ وَالْإِيمَانِ، وَالسَّلَامَةِ وَالْإِسْلَامِ، وَجِوَارٍ مِنَ الشَّيْطَانِ، وَرِضْوَانٍ مِنَ الرَّحْمَنِ»',
        duasAr: const [
